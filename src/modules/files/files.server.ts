import { env } from 'cloudflare:workers'
import { z } from 'zod'
import { database } from '@/server/database.server'
import { boundedBytes, body, HttpError, json } from '@/server/http.server'
import { fileLimits, imageType, fileContentPath, type FileAsset, type ImageType } from './policy'
import type { BillingLock } from '@/modules/billing/deletion.server'

type Row = {
  id: string
  user_id: string
  object_key: string
  name: string
  content_type: ImageType
  size: number
  state: FileAsset['state']
  created_at: number
}
const openAccount =
  "EXISTS (SELECT 1 FROM user WHERE id=? AND NOT EXISTS(SELECT 1 FROM account_access WHERE user_id=user.id AND disabled_at IS NOT NULL)) AND NOT EXISTS (SELECT 1 FROM billing_account_state WHERE user_id=? AND (closed_at IS NOT NULL OR lock_until>unixepoch('subsec')*1000))"
const heldAccount =
  "EXISTS (SELECT 1 FROM billing_account_state WHERE user_id=? AND lock_id=? AND closed_at IS NULL AND lock_until>unixepoch('subsec')*1000)"
export function filesConfigured() {
  const value: unknown = Reflect.get(env, 'ASSETS_BUCKET')
  return (
    !!value &&
    typeof value === 'object' &&
    ['put', 'get', 'head', 'delete'].every((name) => typeof Reflect.get(value, name) === 'function')
  )
}
export function assetBucket(): R2Bucket {
  if (!filesConfigured()) throw new HttpError(503, '图片存储暂不可用。')
  // The binding type is generated by Wrangler; this also supports products without an optional binding.
  const binding: unknown = Reflect.get(env, 'ASSETS_BUCKET')
  return binding as R2Bucket
}
async function owned(userId: string, id: string): Promise<Row> {
  const row = await database()
    .prepare('SELECT * FROM file_asset WHERE user_id=? AND id=?')
    .bind(userId, id)
    .first<Row>()
  if (!row) throw new HttpError(404, '图片不存在。')
  return row
}
const references =
  "(SELECT COUNT(*) FROM project WHERE user_id=file_asset.user_id AND cover_asset_id=file_asset.id) + (SELECT COUNT(*) FROM user WHERE id=file_asset.user_id AND image='/api/files/'||file_asset.id||'/content')"
async function list(userId: string) {
  const rows = await database()
    .prepare(
      `SELECT id,name,content_type AS type,size,state,created_at AS createdAt,${references} AS refs FROM file_asset WHERE user_id=? ORDER BY created_at DESC,id LIMIT 101`,
    )
    .bind(userId)
    .all<Omit<FileAsset, 'contentUrl' | 'references'> & { refs: number }>()
  if (rows.results.length > 100) throw new HttpError(413, '图片数量超出当前处理上限。')
  return json({
    configured: filesConfigured(),
    limits: fileLimits,
    files: rows.results.map(({ refs, ...row }) => ({
      ...row,
      contentUrl: row.state === 'ready' ? fileContentPath(row.id) : null,
      references: refs,
    })),
  })
}
async function upload(request: Request, userId: string) {
  const store = assetBucket()
  const data = await boundedBytes(request, fileLimits.maxFileBytes)
  const type = imageType(data)
  if (!type || type !== request.headers.get('content-type'))
    throw new HttpError(400, '仅支持文件头匹配的 PNG、JPEG 或 WebP 图片。')
  let name: string
  try {
    name = decodeURIComponent(request.headers.get('x-file-name') ?? '')
      .normalize('NFC')
      .trim()
  } catch {
    throw new HttpError(400, '图片名称无效。')
  }
  if (!name || name.length > 160 || /[\x00-\x1f\x7f/\\]/.test(name))
    throw new HttpError(400, '图片名称无效。')
  const id = crypto.randomUUID(),
    key = 'private/' + id,
    now = Date.now(),
    db = database()
  const reserved = await db
    .prepare(
      `INSERT INTO file_asset (id,user_id,object_key,name,content_type,size,state,created_at) SELECT ?,?,?,?,?,?,'pending',? WHERE ${openAccount} AND (SELECT COUNT(*) FROM file_asset WHERE user_id=?)<? AND (SELECT COALESCE(SUM(size),0) FROM file_asset WHERE user_id=?)+?<=?`,
    )
    .bind(
      id,
      userId,
      key,
      name,
      type,
      data.byteLength,
      now,
      userId,
      userId,
      userId,
      fileLimits.maxFiles,
      userId,
      data.byteLength,
      fileLimits.maxTotalBytes,
    )
    .run()
  if (!reserved.meta.changes) throw new HttpError(409, '图片配额已满或账号正在核对注销条件。')
  try {
    const object = await store.put(key, data, {
      httpMetadata: { contentType: type },
      customMetadata: { assetId: id },
    })
    if (object.size !== data.byteLength) throw new Error('Unverified storage result')
    await complete(userId, id)
    return json({ id }, 201)
  } catch (error) {
    if (error instanceof HttpError) throw error
    // Keep ambiguous writes pending. Their reserved bytes remain charged until verified cleanup.
    throw new HttpError(503, '上传状态待核对，请在资源库检查；不要重复上传。')
  }
}
async function complete(userId: string, id: string) {
  const db = database()
  const result = await db
    .prepare(
      "UPDATE file_asset SET state='ready' WHERE id=? AND user_id=? AND state='pending' AND EXISTS (SELECT 1 FROM user WHERE id=?) AND NOT EXISTS (SELECT 1 FROM billing_account_state WHERE user_id=? AND closed_at IS NOT NULL)",
    )
    .bind(id, userId, userId, userId)
    .run()
  if (!result.meta.changes && (await owned(userId, id)).state !== 'ready')
    throw new HttpError(409, '图片状态已变化，请刷新资源库。')
}
async function reconcile(userId: string, id: string) {
  const row = await owned(userId, id)
  if (row.state !== 'pending') throw new HttpError(409, '图片状态已变化，请刷新资源库。')
  const object = await assetBucket().head(row.object_key)
  if (
    !object ||
    object.size !== row.size ||
    object.httpMetadata?.contentType !== row.content_type ||
    object.customMetadata?.assetId !== id
  )
    throw new HttpError(409, '上传仍未确认，请稍后检查或联系站点支持。')
  await complete(userId, id)
  return json({ ok: true })
}
async function remove(userId: string, id: string) {
  const row = await owned(userId, id),
    db = database(),
    store = assetBucket()
  const result = await db
    .prepare(
      `UPDATE file_asset SET state='deleting' WHERE id=? AND user_id=? AND state IN ('ready','deleting') AND ${openAccount} AND (${references})=0`,
    )
    .bind(id, userId, userId, userId)
    .run()
  if (!result.meta.changes)
    throw new HttpError(409, '请先移除图片引用，或核对未完成上传及账号状态。')
  try {
    await store.delete(row.object_key)
  } catch {
    throw new HttpError(503, '图片清理尚未完成，请重试删除。')
  }
  await db
    .prepare("DELETE FROM file_asset WHERE user_id=? AND id=? AND state='deleting'")
    .bind(userId, id)
    .run()
  return json({ ok: true })
}
async function avatar(request: Request, userId: string) {
  const input = await body(request, z.object({ assetId: z.uuid().nullable() }).strict()),
    db = database()
  const result = await db
    .prepare(
      `UPDATE user SET image=?,updated_at=? WHERE id=? AND ${openAccount} AND (? IS NULL OR EXISTS (SELECT 1 FROM file_asset WHERE user_id=? AND id=? AND state='ready'))`,
    )
    .bind(
      input.assetId ? fileContentPath(input.assetId) : null,
      Date.now(),
      userId,
      userId,
      userId,
      input.assetId,
      userId,
      input.assetId,
    )
    .run()
  if (!result.meta.changes) throw new HttpError(409, '图片不可用或账号状态已变化。')
  return json({ ok: true })
}
export async function handleFiles(request: Request, userId: string): Promise<Response> {
  const path = new URL(request.url).pathname,
    method = request.method
  if (path === '/api/files') {
    if (method === 'GET') return list(userId)
    if (method === 'POST') return upload(request, userId)
  }
  if (path === '/api/files/avatar' && method === 'POST') return avatar(request, userId)
  const match = /^\/api\/files\/([a-f0-9-]{36})(?:\/(content|reconcile))?$/.exec(path)
  if (!match) throw new HttpError(404, '接口不存在')
  const id = match[1]!
  if (match[2] === 'reconcile' && method === 'POST') return reconcile(userId, id)
  if (!match[2] && method === 'DELETE') return remove(userId, id)
  if (match[2] === 'content' && (method === 'GET' || method === 'HEAD')) {
    const row = await owned(userId, id)
    if (row.state !== 'ready') throw new HttpError(404, '图片不存在。')
    const object = await assetBucket().get(row.object_key)
    if (!object) throw new HttpError(404, '图片不存在。')
    if (method === 'HEAD') await object.body.cancel()
    return new Response(method === 'HEAD' ? null : object.body, {
      headers: {
        'Content-Type': row.content_type,
        'Content-Length': String(object.size),
        'Cache-Control': 'private, no-store',
        'X-Content-Type-Options': 'nosniff',
        'Content-Security-Policy': "default-src 'none'; sandbox",
        'Content-Disposition': `inline; filename*=UTF-8''${encodeURIComponent(row.name)}`,
      },
    })
  }
  throw new HttpError(404, '接口不存在')
}

// Holds the existing account lease. No user is deleted until storage cleanup is confirmed.
// Storage and D1 are not one transaction: partial cleanup can remove files while retaining the account.
export async function cleanAccountFiles(lock: BillingLock) {
  const db = database()
  const rows = await db
    .prepare('SELECT id,object_key,state FROM file_asset WHERE user_id=? ORDER BY id LIMIT 101')
    .bind(lock.userId)
    .all<{ id: string; object_key: string; state: string }>()
  if (!rows.results.length) return
  if (rows.results.length > 100 || rows.results.some((row) => row.state === 'pending'))
    throw new HttpError(409, '请先核对资源库中未完成的上传，再注销账号。')
  const store = assetBucket()
  const marked = await db
    .prepare(`UPDATE file_asset SET state='deleting' WHERE user_id=? AND ${heldAccount}`)
    .bind(lock.userId, lock.userId, lock.id)
    .run()
  if (marked.meta.changes !== rows.results.length)
    throw new HttpError(409, '账号状态已变化，请重新核对。')
  try {
    await store.delete(rows.results.map((row) => row.object_key))
  } catch {
    throw new HttpError(503, '图片清理尚未完成，请重试删除。')
  }
  await db.batch([
    db
      .prepare(
        `UPDATE user SET image=NULL WHERE id=? AND image IN (SELECT '/api/files/'||id||'/content' FROM file_asset WHERE user_id=?) AND ${heldAccount}`,
      )
      .bind(lock.userId, lock.userId, lock.userId, lock.id),
    db
      .prepare(`DELETE FROM file_asset WHERE user_id=? AND state='deleting' AND ${heldAccount}`)
      .bind(lock.userId, lock.userId, lock.id),
  ])
  if (
    await db.prepare('SELECT id FROM file_asset WHERE user_id=? LIMIT 1').bind(lock.userId).first()
  )
    throw new HttpError(409, '账号状态已变化，请重新核对。')
}
